export const catalogs = {
  es: esCatalog,
  en: enCatalog,
} as const;

export type MessageId = keyof typeof esCatalog;

const formatterCache = new Map<string, IntlMessageFormat>();

export function resolveLocale(input?: string | null): SupportedLocale {
  if (typeof input !== 'string') return defaultSupportedLocale;
  const normalized = input.trim().toLowerCase().split(/[-_]/)[0];
  return resolveSupportedLocale(normalized);
}

export function resolveLocaleFromCandidates(candidates: Array<string | null | undefined>): SupportedLocale {
  for (const candidate of candidates) {
    if (typeof candidate !== 'string' || !candidate.trim()) continue;
    const locale = resolveLocale(candidate);
    if (locale !== defaultSupportedLocale || candidate.trim().toLowerCase().split(/[-_]/)[0] === defaultSupportedLocale) {
      return locale;
    }
  }

  return defaultSupportedLocale;
}

export function formatMessage(locale: string | null | undefined, id: MessageId, values: MessageValues = {}): string {
  const resolvedLocale = resolveLocale(locale);
  const message = catalogs[resolvedLocale][id] ?? catalogs[fallbackSupportedLocale][id];
  const cacheKey = `${resolvedLocale}:${id}`;
  let formatter = formatterCache.get(cacheKey);
  if (!formatter) {
    formatter = new IntlMessageFormat(message, resolvedLocale);
    formatterCache.set(cacheKey, formatter);
  }
  return String(formatter.format(values));
}

export function assertCatalogParity(): void {
  const referenceKeys = Object.keys(catalogs[defaultSupportedLocale]).sort();
  for (const locale of supportedLocales) {
    const keys = Object.keys(catalogs[locale]).sort();
    if (JSON.stringify(keys) !== JSON.stringify(referenceKeys)) {
      throw new Error(`Catalog ${locale} keys differ from ${defaultSupportedLocale}`);
    }
  }
}
